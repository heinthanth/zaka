use zakac_diagnostics::Code;

use crate::common::codes;
use crate::common::ok;

/// A function whose body is `body`, run once from the start block.
fn in_fn(body: &str) -> String
{
    format!(
        "စမ်း ဟူသော လုပ်ဆောင်ချက် သည် အောက်ပါတို့ကို လုပ်ဆောင်မည်။\n{body}\nလုပ်ဆောင်စရာများ \
         ပြီးဆုံးပါပြီး။\nစမ်း ဟူသော လုပ်ဆောင်ချက်ကို လုပ်ဆောင်မည်။"
    )
}

#[test]
fn marked_code_that_would_leave_its_block_is_zk0365()
{
    let ret = in_fn("လုပ်ဆောင်စရာများပြီးသည့် အခါတွင် ပြန်ပေးမည်။");
    assert_eq!(codes(&ret), [Code::DeferLeaves]);
    let brk = "၁ မှ ၃ အထိ န အနေဖြင့် ရေတွက်၍ အောက်ပါတို့ကို လုပ်ဆောင်မည်။\nလုပ်ဆောင်စရာများပြီးသည့် အခါတွင် \
               အောက်ပါတို့ကို လုပ်ဆောင်မည်။\nကွင်းဆက် ကို ရပ်မည်။\nလုပ်ဆောင်စရာများ \
               ပြီးဆုံးပါပြီး။\nလုပ်ဆောင်စရာများ ပြီးဆုံးပါပြီး။";
    assert_eq!(codes(brk), [Code::DeferLeaves]);
    let next = brk.replace("ကွင်းဆက် ကို ရပ်မည်။", "နောက်တစ်ကြိမ်ဆီသို့ ကျော်မည်။");
    assert_eq!(codes(&next), [Code::DeferLeaves]);
}

