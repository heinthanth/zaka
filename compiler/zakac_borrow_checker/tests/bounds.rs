/// The text of a repo file.
fn repo_file(path: &str) -> String
{
    let root = concat!(env!("CARGO_MANIFEST_DIR"), "/../../");
    std::fs::read_to_string(format!("{root}{path}")).unwrap()
}

/// The folded module of a text with no error.
fn module(text: &str) -> Module
{
    let run = run(text);
    run.out.lowered.folded.expect("the text lowers")
}

/// The message of the first diagnostic of a text.
fn first_message(text: &str) -> String
{
    let run = run(text);
    run.out.diagnostics.first().expect("a diagnostic").message.clone()
}

