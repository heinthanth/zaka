/// Each statement of each routine of a module, one form each.
fn all_forms(module: &Module) -> String
{
    let routines = module.funcs.iter().map(|f| &f.block).chain([&module.main]);
    let forms =
        routines.flat_map(|b| b.iter().map(zakac_ast::s_expr::ToSexpr::to_sexpr));
    forms.collect::<Vec<String>>().join("\n")
}

/// Assert that a text is clean and that each cell marked checked has a
/// constant cell number, which the fold proves on its own.
fn clean_and_unchecked(text: &str)
{
    ok(text);
    let forms = all_forms(&module(text));
    for (n, _) in forms.match_indices(" checked)")
    {
        let words: Vec<&str> = forms[..n].split_whitespace().collect();
        let index = words[words.len() - 2];
        let constant = index.contains(':') && !index.ends_with(')');
        assert!(constant, "a cell number {index} is proven: {forms}");
    }
}

