#[test]
fn null_flows_through_a_lend()
{
    let text = "\
ကိန်းရှင် ပ သည် ကိန်းပြည့် လိပ်စာ ဖြစ်ပါစေ။
ကိန်းရှင် q သည် ငှားထားသော ကိန်းပြည့် လိပ်စာ ဖြစ်၍ တန်ဖိုးသည် ပ ၏ တန်ဖိုးအငှား ဖြစ်ပါစေ။
q ၏ တန်ဖိုး ကို ပြသပါ။
";
    assert_eq!(lines(text), [(Code::NullDeref, 3)]);
    let run = common::run(text);
    assert!(
        run.out.diagnostics[0].message.contains("\"q\""),
        "{:?}",
        run.out.diagnostics
    );
}

