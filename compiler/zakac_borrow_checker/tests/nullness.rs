#[test]
fn definite_null_is_zk0709()
{
    let text = "\
ကိန်းရှင် ဂ သည် ကိန်းပြည့် လိပ်စာ ဖြစ်ပါစေ။
ဂ ၏ တန်ဖိုး ကို ပြသပါ။
ကိန်းရှင် ပ သည် ကိန်းပြည့် လိပ်စာ ဖြစ်ပါစေ။ မင်မိုရီတွင် ကိန်းပြည့် ၁ ခုစာ နေရာယူ၍ လိပ်စာကို ပ တွင် သိမ်းထားမည်။
လိပ်စာ ပ ရှိ မင်မိုရီကို ပြန်လည်စွန့်လွှတ်မည်။
ပ ၏ တန်ဖိုး ကို ပြသပါ။
";
    assert_eq!(lines(text), [(Code::NullDeref, 2), (Code::NullDeref, 5)]);
}

