#[test]
fn possible_null_is_zk0711_under_strict()
{
    assert_eq!(codes(UNTESTED), []);
    let run = run_with(UNTESTED, &strict());
    let found: Vec<(Code, Level)> =
        run.out.diagnostics.iter().map(|d| (d.code, d.level)).collect();
    assert_eq!(found, [(Code::NullDerefPossible, Level::Warning)]);
}

