#[test]
fn null_flows_through_a_lend()
{
    let text = "\
ပရိုဂရမ်သည် အောက်ပါတို့ကို လုပ်ဆောင်မည်။
ကိန်းရှင် ပ သည် ကိန်းပြည့် လိပ်စာ တစ်ခု ဖြစ်၍ တန်ဖိုးသည် ကနဦးတန်ဖိုး ဖြစ်ပါစေ။
ကိန်းရှင် q သည် ကိန်းပြည့် လိပ်စာ တစ်ခု ဖြစ်၍ တန်ဖိုးသည် ပ ဖြစ်ပါစေ။
q ၏ တန်ဖိုး ကို ပြသမည်။
ပရိုဂရမ် ပြီးဆုံးပါပြီး။
";
    assert_eq!(lines(text), [(Code::NullDeref, 4)]);
    let run = common::run(text);
    assert!(
        run.out.diagnostics[0].message.contains("\"q\""),
        "{:?}",
        run.out.diagnostics
    );
}

