#[test]
fn a_closure_that_owns_a_block_moves_and_is_lent_but_is_no_duplicate()
{
    let own = "လုပ်ဆောင်ချက် ကိုင် သည် ပ ကို အပိုင်အနေဖြင့်လည်းကောင်း လက်ခံပြီး အောက်ပါတို့ကို လုပ်ဆောင်မည်။
ပ ၏ တန်ဖိုး ကို ပြသပါ။
လုပ်ဆောင်စရာများ ပြီးဆုံးပါပြီး။
";
    let moved = format!(
        "{own}လုပ်ဆောင်ချက် ခေါ် ကို လုပ်ဆောင်ချက် ကိုင် ၏ လိပ်စာ တို့ဖြင့် လုပ်ဆောင်ပါ။
ကိန်းရှင် ရွှေ့ ထဲသို့ လုပ်ဆောင်ချက် ကိုင် ၏ လိပ်စာ ကို ပြောင်းထည့်မည်။
လုပ်ဆောင်ချက် ရွှေ့ ကို လုပ်ဆောင်ပါ။
"
    );
    ok(&program(&moved));
    let twice = format!(
        "{own}ကိန်းရှင် ပွား ထဲသို့ လုပ်ဆောင်ချက် ကိုင် ၏ လိပ်စာ ကို ကူးထည့်မည်။
လုပ်ဆောင်ချက် ကိုင် ကို လုပ်ဆောင်ပါ။
လုပ်ဆောင်ချက် ပွား ကို လုပ်ဆောင်ပါ။
"
    );
    assert_eq!(codes(&program(&twice)), [Code::ClosureOwnerDup]);
}
