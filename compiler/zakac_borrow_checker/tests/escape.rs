#[test]
fn borrow_param_returned_is_fine()
{
    let text = "\
// အကွက်များထဲမှ အကြီးဆုံး ကိန်း၏ လိပ်စာ
လုပ်ဆောင်ချက် အကြီးဆုံး သည်
က ဟူသော ကိန်းပြည့် လိပ်စာ တစ်ခု ကို လည်းကောင်း အရေအတွက် ဟူသော ကိန်းပြည့် တစ်ခု ကို လည်းကောင်း လက်ခံပြီး
အောက်ပါတို့ကို လုပ်ဆောင်ကာ ကိန်းပြည့် လိပ်စာ တစ်ခု ကို ပြန်ပေးမည်။
ကိန်းရှင် အဖြေ သည် ကိန်းပြည့် လိပ်စာ တစ်ခု ဖြစ်၍ တန်ဖိုးသည် က ဖြစ်ပါစေ။
၁ မှ အရေအတွက် - ၁ အထိ န အနေဖြင့် ရေတွက်၍ အောက်ပါတို့ကို လုပ်ဆောင်မည်။
အကယ်၍ (က + န) ၏ တန်ဖိုး သည် အဖြေ ၏ တန်ဖိုး ထက် ကြီးလျှင် အဖြေ ကို က + န ဟု ထားမည်။
လုပ်ဆောင်စရာများ ပြီးပါပြီး။
အဖြေ ကို ပြန်ပေးမည်။
လုပ်ဆောင်စရာများ ပြီးပါပြီး။

လုပ်ဆောင်ချက် ပထမ သည်
က ဟူသော ကိန်းပြည့် လိပ်စာ တစ်ခု ကို လည်းကောင်း ခ ဟူသော ကိန်းပြည့် လိပ်စာ တစ်ခု ကို လည်းကောင်း လက်ခံပြီး
အောက်ပါတို့ကို လုပ်ဆောင်ကာ ကိန်းပြည့် လိပ်စာ တစ်ခု ကို ပြန်ပေးမည်။
ခ ကို ပြန်ပေးမည်။
လုပ်ဆောင်စရာများ ပြီးပါပြီး။
";
    ok(text);
    let digests = run(text).out.digests;
    let from: Vec<(Vec<u32>, bool)> =
        digests.iter().map(|d| (d.result_from.clone(), d.result_roots_ok)).collect();
    assert_eq!(from, [(vec![0], true), (vec![1], true), (vec![], true)]);
}

