#[test]
fn owner_result_from_alloc_is_fine()
{
    let text = "\
လုပ်ဆောင်ချက် ဂဏန်း သည်
အောက်ပါတို့ကို လုပ်ဆောင်ကာ ကိန်းပြည့် လိပ်စာ တစ်ခု ကို ပြန်ပေးမည်။
ကိန်းရှင် အဖြေ သည် ကိန်းပြည့် လိပ်စာ တစ်ခု ဖြစ်ပါစေ။
မင်မိုရီတွင် ကိန်းပြည့် ၁ ခုစာ နေရာယူ၍ လိပ်စာကို အဖြေ တွင် သိမ်းထားမည်။
အဖြေ ၏ တန်ဖိုး ကို ၅ ဟု ထားမည်။
အဖြေ ကို ပြန်ပေးမည်။
လုပ်ဆောင်စရာများ ပြီးပါပြီး။
";
    ok(&text.replace("တစ်ခု ကို ပြန်ပေးမည်", "တစ်ခု ကို အပိုင်အနေဖြင့် ပြန်ပေးမည်"));
    // An unmarked result made here leaks, with the help to mark it.
    assert_eq!(lines(text), [(Code::BlockLeaked, 6)]);
    let help = run(text).out.diagnostics[0].help.clone().unwrap_or_default();
    assert!(help.contains("အပိုင်အနေဖြင့်"), "{help}");
}

