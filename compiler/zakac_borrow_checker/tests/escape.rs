#[test]
fn local_borrow_returned_is_zk0706()
{
    let text = "\
လုပ်ဆောင်ချက် ဂဏန်း သည်
အောက်ပါတို့ကို လုပ်ဆောင်ကာ ငှားထားသော ကိန်းပြည့် လိပ်စာ ရလဒ် ကို ပြန်ပေးမည်။
ကိန်းရှင် x သည် ကိန်းပြည့် ၅ ဖြစ်ပါစေ။
ကိန်းရှင် ပ သည် ငှားထားသော ကိန်းပြည့် လိပ်စာ ဖြစ်၍ တန်ဖိုးသည် x ၏ လိပ်စာ ဖြစ်ပါစေ။
ပ ကို ရလဒ်အဖြစ် ပြန်ပေးပါ။
လုပ်ဆောင်စရာများ ပြီးပါပြီး။
";
    assert_eq!(lines(text), [(Code::LocalBorrowReturned, 5)]);
    let found = run(text);
    let message = &found.out.diagnostics[0].message;
    assert!(message.contains("\"x\""), "{message}");
    assert!(!found.out.digests[0].result_roots_ok);
}

