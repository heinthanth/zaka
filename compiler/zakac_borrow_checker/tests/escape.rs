#[test]
fn borrow_param_returned_is_fine()
{
    let text = "\
// အကွက်များထဲမှ အကြီးဆုံး ကိန်း၏ လိပ်စာ
လုပ်ဆောင်ချက် အကြီးဆုံး သည်
ငှားထားသော ကိန်းပြည့် လိပ်စာ က နှင့် ကိန်းပြည့် အရေအတွက် တို့ကို လက်ခံပြီး
အောက်ပါတို့ကို လုပ်ဆောင်ကာ ငှားထားသော ကိန်းပြည့် လိပ်စာ ရလဒ် ကို ပြန်ပေးမည်။
ရလဒ် ကို က ဟု ထားပါ။
၁ မှ အရေအတွက် - ၁ အထိ န အနေဖြင့် ရေတွက်၍ အောက်ပါတို့ကို လုပ်ဆောင်ပါ။
အကယ်၍ (က + န) ၏ တန်ဖိုး သည် ရလဒ် ၏ တန်ဖိုး ထက် ကြီးလျှင် ရလဒ် ကို က + န ဟု ထားပါ။
လုပ်ဆောင်စရာများ ပြီးပါပြီး။
လုပ်ဆောင်စရာများ ပြီးပါပြီး။

လုပ်ဆောင်ချက် ပထမ သည်
ငှားထားသော ကိန်းပြည့် လိပ်စာ က နှင့် ငှားထားသော ကိန်းပြည့် လိပ်စာ ခ တို့ကို လက်ခံပြီး
အောက်ပါတို့ကို လုပ်ဆောင်ကာ ငှားထားသော ကိန်းပြည့် လိပ်စာ ရလဒ် ကို ပြန်ပေးမည်။
ခ ကို ရလဒ်အဖြစ် ပြန်ပေးပါ။
လုပ်ဆောင်စရာများ ပြီးပါပြီး။
";
    ok(text);
    let digests = run(text).out.digests;
    let from: Vec<(Vec<u32>, bool)> =
        digests.iter().map(|d| (d.result_from.clone(), d.result_roots_ok)).collect();
    assert_eq!(from, [(vec![0], true), (vec![1], true)]);
}

