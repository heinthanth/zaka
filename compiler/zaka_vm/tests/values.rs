/// The check works out a list count, and the same expression as a
/// constant is folded and run: each form of expression a count takes gives
/// the two the same number.
#[test]
fn counts_agree_with_the_values_the_program_computes()
{
    let forms = [
        "(N + ၁) * ၂ - N % ၂",
        "N << ၂",
        "(N & ၆) | ၁",
        "N ^ ၇",
        "~(-N)",
        "B / ၃",
        "N နှင့် ၂ ၏ ပေါင်းလဒ်",
        "၂.၇ ကို ကိန်းပြည့် တစ်ခု အဖြစ် ပြောင်းလဲသော ရလဒ်",
        "('A' ကို ကိန်းပြည့် တစ်ခု အဖြစ် ပြောင်းလဲသော ရလဒ်) - ၆၀",
        "ကိန်းပြည့် တစ်ခု ၏ အရွယ်အစား",
        "နေရာ တစ်ခု ၏ အရွယ်အစား",
        "အကွက် N ခုရှိသော ၁၆ ဘစ် ကိန်းပြည့် စာရင်း တစ်ခု ၏ အရွယ်အစား",
        "L ၏ အကွက် ၁",
        "C ၏ ၃ ခုမြောက်အကွက်",
        "(P ၏ x) + (P ၏ y)",
        "T ၏ အကွက် ၁ ၏ အကွက် ၀",
        "L ၏ အကွက်အရေအတွက်",
        "v ၏ အကွက်အရေအတွက်",
        "(w ၏ အကွက်အရေအတွက်) + ၁",
    ];
    for form in forms
    {
        let program = format!(
            "{AGREES_HEAD}ကိန်းသေ K သည် {form} ဖြစ်ပါစေ။
ကိန်းရှင် l သည် အကွက် {form} ခုရှိသော ၈ ဘစ် ကိန်းပြည့် စာရင်း တစ်ခု ဖြစ်ပါစေ။
K ကို ပြသမည်။
l ၏ အကွက်အရေအတွက် ကို ပြသမည်။"
        );
        let module =
            compile_text(&program, &FoldOptions::default(), EmitOptions::default());
        let mut out = Vec::new();
        let options = RunOptions::default();
        let (_, result) =
            run_and_keep(&module, &mut out, &options, &HostData::default());
        assert_eq!(result, Ok(()), "{form}");
        let out = String::from_utf8(out).unwrap();
        let lines: Vec<&str> = out.lines().collect();
        assert_eq!(lines.len(), 2, "{form}: {out}");
        assert_eq!(lines[0], lines[1], "{form}");
    }
}

/// A chain of 20,000 objects: the equal test and the print walk it with
/// lists of their own, so the depth takes no stack.
#[test]
fn a_long_chain_of_objects_compares_and_prints()
{
    let text = "အဆစ် ဟူသော မျှဝေနိုင်သော ဒေတာအစုအဝေးတွင် တန် ဟူသော ကိန်းပြည့် တစ်ခု၊ နောက် ဟူသော အဆစ် \
                ရှိကောင်းရှိနိုင်သော ဒေတာဆဲလ် တစ်ခု တို့ပါဝင်သည်။
ပရိုဂရမ်သည် အောက်ပါတို့ကို လုပ်ဆောင်မည်။
ကိန်းရှင် က သည် အဆစ်(တန်: ၀၊ နောက်: အလွတ်) ဖြစ်ပါစေ။
ကိန်းရှင် ခ သည် အဆစ်(တန်: ၀၊ နောက်: အလွတ်) ဖြစ်ပါစေ။
၁ မှ ၂၀၀၀၀ အထိ န အနေဖြင့် ရေတွက်၍ အောက်ပါတို့ကို လုပ်ဆောင်မည်။
က ကို အဆစ်(တန်: န၊ နောက်: က) ဟု ထားမည်။
ခ ကို အဆစ်(တန်: န၊ နောက်: ခ) ဟု ထားမည်။
လုပ်ဆောင်စရာများ ပြီးဆုံးပါပြီး။
က == ခ ကို ပြသမည်။
က ကို ပြသမည်။
ပရိုဂရမ် ပြီးဆုံးပါပြီး။";
    let options = RunOptions::builder().max_steps(50_000_000).build();
    let (out, result) = run_source_with(text, &options);
    assert_eq!(result, Ok(()));
    let mut lines = out.lines();
    assert_eq!(lines.next(), Some("မှန်"));
    let shown = lines.next().expect("the chain prints");
    assert_eq!(shown.matches("အဆစ်(").count(), 20_001);
}
