//! Structs based on other structs on the VM: fields and functions of the
//! parts, an own function that wins, parts of parts, traits through parts,
//! and trait values that change the duplicate of a part.

use zaka_vm::machine::HostData;
use zaka_vm::machine::RunOptions;
use zaka_vm::machine::run_and_keep;

use crate::common::compile;

/// Run a program and give its output, after a check that no block leaks.
///
/// # Arguments
///
/// * `text` - The program.
///
/// # Returns
///
/// The output.
fn run_clean(text: &str) -> String
{
    let module = compile(text);
    let mut out = Vec::new();
    let (machine, result) =
        run_and_keep(&module, &mut out, &RunOptions::default(), &HostData::default());
    assert!(result.is_ok(), "{result:?}");
    assert_eq!(machine.leaks(), []);
    String::from_utf8(out).unwrap()
}

